/**
 * 별점(rating)과 책 카테고리에 맞는 한줄 리뷰 문장을 고른다. 카테고리 전용 문구가 있으면
 * 45% 확률로 섞어 쓰고, 그 외엔 어떤 책에도 자연스러운 범용 문구를 쓴다 — 같은 카테고리
 * 책끼리도 문장이 겹치지 않게 다양성을 유지하기 위함이다.
 */
export function pickReviewContent(category: string, rating: ReviewTier): string {
  const categoryPool = BY_CATEGORY[category]?.[rating]
  if (categoryPool && categoryPool.length > 0 && Math.random() < 0.45) {
    return pick(categoryPool)
  }
  return pick(GENERIC[rating])
}

/**
 * 책 1권당 목표 리뷰 수를 가중 랜덤으로 정한다 — "책마다 리뷰가 엄청 많이" 달려 있으면서도
 * 전부 똑같이 많으면 부자연스러우니, 대부분은 2~6개, 일부는 인기 도서처럼 몰아준다.
 * seed.ts(전체 리시드)와 enrich-reviews.ts(추가 시딩) 양쪽에서 같은 분포를 쓴다.
 */
export function targetReviewCount(): number {
  const r = Math.random()
  if (r < 0.08) return randomInt(1, 2) // 조용한 책 8%
  if (r < 0.75) return randomInt(2, 6) // 보통 67%
  if (r < 0.92) return randomInt(6, 10) // 인기 17%
  return randomInt(10, 16) // 베스트셀러급 8%
}
