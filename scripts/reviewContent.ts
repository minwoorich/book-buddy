// 양쪽에서 공유한다 — "책마다 다양하고 그럴듯한 리뷰"를 위해 별점 등급(1~5)별 톤이 다른
// 범용 문장 풀과, 4개 카테고리 전용 문장 풀을 함께 둔다.

function randomInt(min: number, max: number): number {
  return Math.floor(Math.random() * (max - min + 1)) + min
}

function pick<T>(arr: T[]): T {
  return arr[randomInt(0, arr.length - 1)]
}

export type ReviewTier = 1 | 2 | 3 | 4 | 5

// 실제 리뷰 서비스처럼 높은 점수 쪽에 치우친 분포(5점 32% ~ 1점 5%).
const RATING_WEIGHTS: [ReviewTier, number][] = [
  [5, 32],
  [4, 34],
  [3, 20],
  [2, 9],
  [1, 5],
]

/** 가중 랜덤 별점(1~5)을 뽑는다. */
export function pickWeightedRating(): ReviewTier {
  const total = RATING_WEIGHTS.reduce((sum, [, weight]) => sum + weight, 0)
  let roll = Math.random() * total
  for (const [rating, weight] of RATING_WEIGHTS) {
    if (roll < weight) return rating
    roll -= weight
  }
  return 3
}

